/**
 * Fetch a random poetry piece or cycle through by index
 */
export function getRandomPoetryPiece(): PoetryPiece {
  const index = Math.floor(Math.random() * CLASSICAL_POETRY_COLLECTION.length);
  return CLASSICAL_POETRY_COLLECTION[index];
}

/**
 * Fetch poetry pieces by era or theme
 */
export function getPoetryByEra(era: string): PoetryPiece[] {
  return CLASSICAL_POETRY_COLLECTION.filter((p) => p.era === era);
}
